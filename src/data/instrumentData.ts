/**
 * URL of a file in `public/` (the instrument icons are served from there as they are, so the
 * paths work in a build and under any base path).
 */
export function publicUrl(path: string): string {
  return `${import.meta.env.BASE_URL}${path}`
}

/** Icon of an instrument, or '' for an unknown one. */
export function instrumentIconSrc(instrument: string | undefined): string {
  const path = instrument != null ? instrumentList[instrument]?.[0] : undefined
  return path ? publicUrl(path) : ''
}
