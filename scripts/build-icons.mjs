#!/usr/bin/env node
// Builds src/assets/icons/icons.ts from the SVGs in src/assets/icons/source (npm run icons).
// Every icon is drawn in currentColor, so it follows the text colour in each state and theme:
// dark ink becomes currentColor, mid greys currentColor with reduced opacity. Any other colour
// (white knockouts, real colours) fails the build; redraw such an icon instead.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { optimize } from 'svgo'

const SOURCE = 'src/assets/icons/source'
const OUT = 'src/assets/icons/icons.ts'
const ROOT_PAINT = ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin']

function lightness(color) {
  const named = { black: '#000000', white: '#ffffff' }
  let hex = (named[color.toLowerCase()] ?? color).replace('#', '')
  if (!/^[0-9a-f]{3}([0-9a-f]{3})?$/i.test(hex)) return null
  if (hex.length === 3) hex = [...hex].map((c) => c + c).join('')
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
  return (Math.max(r, g, b) + Math.min(r, g, b)) / 2
}

function themeColors(file) {
  return {
    name: 'themeColors',
    fn: () => ({
      element: {
        enter(node) {
          for (const attr of ['fill', 'stroke', 'stop-color']) {
            const value = node.attributes[attr]
            if (value == null || value === 'none' || value === 'currentColor' || value.startsWith('url('))
              continue
            const l = lightness(value)
            if (l == null || l >= 0.9)
              throw new Error(`${file}: ${attr}="${value}" can't be themed; redraw the icon`)
            node.attributes[attr] = 'currentColor'
            if (l >= 0.55)
              node.attributes[`${attr === 'stop-color' ? 'stop' : attr}-opacity`] = String(
                Math.min(1, Math.round((1 - l) * 160) / 100),
              )
          }
        },
      },
    }),
  }
}

function buildIcon(file) {
  const source = readFileSync(join(SOURCE, file), 'utf8')
  const { data } = optimize(source, {
    multipass: true,
    plugins: [
      {
        name: 'preset-default',
        params: { overrides: { removeViewBox: false, convertColors: { currentColor: false } } },
      },
      'convertStyleToAttrs',
      'removeDimensions',
      themeColors(file),
    ],
  })
  const match = data.match(/^<svg([^>]*)>([\s\S]*)<\/svg>$/)
  if (!match) throw new Error(`${file}: unexpected svgo output`)
  const rootAttrs = Object.fromEntries(
    [...match[1].matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]),
  )
  if (!rootAttrs.viewBox) throw new Error(`${file}: no viewBox`)
  // SVG's default fill is black: shapes and text without a fill would stay black in dark mode.
  if (rootAttrs.fill == null) rootAttrs.fill = 'currentColor'
  const paint = ROOT_PAINT.filter((a) => rootAttrs[a] != null).map((a) => `${a}="${rootAttrs[a]}"`)
  const body = `<g ${paint.join(' ')}>${match[2]}</g>`
  if (/#[0-9a-f]{3,6}\b/i.test(body)) throw new Error(`${file}: colour left after cleaning`)
  return { viewBox: rootAttrs.viewBox, body }
}

const files = readdirSync(SOURCE)
  .filter((f) => f.endsWith('.svg'))
  .sort()
const entries = files.map((file) => {
  const { viewBox, body } = buildIcon(file)
  return `  '${file.replace(/\.svg$/, '')}': { viewBox: '${viewBox}', body: ${JSON.stringify(body)} },`
})
writeFileSync(
  OUT,
  `// Generated by scripts/build-icons.mjs from src/assets/icons/source. Do not edit; run npm run icons.\n` +
    `export const ICONS = {\n${entries.join('\n')}\n} as const\n\n` +
    `export type IconName = keyof typeof ICONS\n`,
)
console.log(`${files.length} icons -> ${OUT}`)
